"""Small PDF presentation layer for the structured persisted safety report."""

from pathlib import Path
from typing import Any

from fpdf import FPDF


def _font_path() -> Path | None:
    for candidate in (
        Path("C:/Windows/Fonts/arial.ttf"),
        Path("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"),
        Path("/usr/share/fonts/dejavu/DejaVuSans.ttf"),
    ):
        if candidate.is_file():
            return candidate
    return None


def _hazard_label(value: str | None) -> str:
    return value.replace("_", " ").title() if value else "Finding unavailable"


def render_safety_report_pdf(report: dict[str, Any]) -> bytes:
    """Render the exact JSON-preview payload as a downloadable PDF document."""
    pdf = FPDF(format="A4")
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()
    font_file = _font_path()
    font = "Helvetica"
    if font_file is not None:
        pdf.add_font("SafeSite", fname=str(font_file))
        font = "SafeSite"

    def line(value: Any, *, size: int = 10, space: int = 0) -> None:
        pdf.set_font(font, size=size)
        text = str(value)
        if font_file is None:
            text = text.encode("latin-1", errors="replace").decode("latin-1")
        pdf.multi_cell(0, 6, text, new_x="LMARGIN", new_y="NEXT")
        if space:
            pdf.ln(space)

    def section(title: str) -> None:
        pdf.ln(3)
        line(title, size=13, space=1)

    scope = report["scope"]
    line("SafeSite Risk Intelligence", size=18)
    line("Safety Intelligence Report", size=15, space=3)
    line(f"Generated: {report['generated_at'].isoformat()}")
    line(f"Generated by: {report['generated_by']['email']} ({report['generated_by']['role']})")
    start = scope["window_start"].isoformat() if scope["window_start"] else "beginning"
    end = scope["window_end"].isoformat() if scope["window_end"] else "present"
    line("Period: All recorded history" if not scope["window_start"] and not scope["window_end"] else f"Period: {start} <= observed_at < {end}")
    areas = "All work areas" if scope["all_work_areas"] else ", ".join(scope["work_areas"])
    if not scope["all_work_areas"] and scope["include_unassigned"]:
        areas = f"{areas}, Unassigned work area" if areas else "Unassigned work area"
    line(f"Work areas: {areas}")

    section("Executive summary")
    for label, key in (
        ("Total observations", "total_observations"),
        ("Supported PPE findings", "supported_ppe_findings"),
        ("Actionable alerts", "actionable_alerts"),
        ("Warnings", "warnings"),
        ("Pending assessments", "pending_assessments"),
        ("Resolved alerts", "resolved_alerts"),
    ):
        line(f"{label}: {report['summary'][key]}")
    if not report["summary"]["total_observations"]:
        line("No recorded SafeSite observations match the selected report scope.")

    section("Safety decisions and risk distribution")
    line("Decision counts (per observation): " + ", ".join(
        f"{key} {value}" for key, value in report["decision_counts"].items()
    ))
    line("Risk distribution (supported finding rows): " + ", ".join(
        f"{key} {value}" for key, value in report["risk_distribution"].items()
    ))

    section("Supported PPE violation breakdown")
    if not report["violation_breakdown"]:
        line("No supported PPE findings in this report scope.")
    for item in report["violation_breakdown"]:
        line(f"{_hazard_label(item['hazard_type'])}: {item['count']}")

    section("Work-area analysis")
    for item in report["work_areas"]:
        line(f"{item['work_area']}: {item['violation_count']} finding rows; common: {_hazard_label(item['most_common_violation']) if item['most_common_violation'] else 'none'}")
    if report["highest_violation_work_areas"]:
        line("Highest recorded PPE-violation count (ties shown): " + ", ".join(report["highest_violation_work_areas"]))
    elif not report["work_areas"]:
        line("No work-area findings in this report scope.")

    section("Repeated violation observations")
    if not report["recurrence"]:
        line("No repeated named-work-area PPE groups in this report scope.")
    for item in report["recurrence"]:
        line(f"{item['work_area']} / {_hazard_label(item['hazard_type'])}: {item['observation_count']} distinct observations ({', '.join(item['observation_ids'])})")

    section("Alert lifecycle")
    line(", ".join(f"{key}: {value}" for key, value in report["alert_status_counts"].items()))
    for item in report["alerts"]:
        line(f"Alert #{item['alert_id']} | Observation {item['observation_id']} | {item['work_area']} | {_hazard_label(item['hazard_type'])} | {item['risk_band'] or 'not scored'} | {item['status']}")
        line("Created: " + item["created_at"].isoformat() + "; acknowledged: " + (item["acknowledged_at"].isoformat() if item["acknowledged_at"] else "-") + "; resolved: " + (item["resolved_at"].isoformat() if item["resolved_at"] else "-") + "; dismissed: " + (item["dismissed_at"].isoformat() if item["dismissed_at"] else "-"))

    section("Detailed supported findings")
    for item in report["findings"]:
        confidence = f"{item['detection_confidence']:.4f}" if item["detection_confidence"] is not None else "unavailable"
        line(f"{item['observation_id']} | {item['observed_at'].isoformat()} | {item['work_area']} | {_hazard_label(item['hazard_type'])} | confidence {confidence} | risk {item['risk_score'] if item['risk_score'] is not None else 'pending'} ({item['risk_band'] or 'not scored'}) | decision {item['safety_decision']} | alert {item['alert_status'] or '-'}")

    section("Important context")
    line(report["disclaimer"])
    line("Work areas are operator-entered text, not verified site or zone identities. Recurrence counts distinct persisted observations and does not modify risk or alert decisions.")
    return bytes(pdf.output())
